type DeepDict = { [k: string]: DeepDict } | { en: string; id: string };

export function translate(dict: DeepDict, lang: Lang, path: string): string {
  const parts = path.split(".");
  let node: DeepDict = dict;
  for (const p of parts) {
    if (typeof node !== "object" || node === null || !(p in node)) return path;
    node = (node as Record<string, DeepDict>)[p];
  }
  if (typeof node === "object" && "en" in node && typeof node.en === "string") {
    return (node as { en: string; id: string })[lang];
  }
  return path;
}
